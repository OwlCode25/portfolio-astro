/**
 * Extracts only the icon paths this site actually uses into src/data/tech-icons.ts.
 *
 * Importing `simple-icons` from a component looks harmless, but this site is
 * SSR: that import runs per request, so the Vercel adapter copies the whole
 * package into the serverless function — 10 MB for 28 icons, 35% of the
 * function. Generating a flat module keeps the payload to a few KB and drops
 * simple-icons to a build-only dependency.
 *
 * Run: npm run icons:gen
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const SLUGS = [
  "python", "rust", "typescript",
  "flask", "django", "fastapi",
  "astro", "react", "tailwindcss", "expo", "tauri",
  "n8n", "apacheairflow", "langchain", "ollama",
  "odoo", "postgresql", "sqlite",
  "docker", "nginx", "vercel", "googlecloud", "git",
  "archlinux", "apple", "hyprland", "neovim", "tmux",
];

const key = (s) => "si" + s.charAt(0).toUpperCase() + s.slice(1);

const entries = SLUGS.map((slug) => {
  const icon = si[key(slug)];
  if (!icon) throw new Error(`simple-icons has no entry for "${slug}"`);
  return `  ${slug}: "${icon.path}",`;
});

writeFileSync(
  "src/data/tech-icons.ts",
  `// GENERATED by scripts/gen-tech-icons.mjs — do not edit by hand.
// Regenerate with: npm run icons:gen
// Source: simple-icons v${si.siPython ? process.env.npm_package_devDependencies_simple_icons ?? "16" : "?"}

export const icons = {
${entries.join("\n")}
} as const;
`,
);

console.log(`wrote src/data/tech-icons.ts with ${entries.length} icons`);
